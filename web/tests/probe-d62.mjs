import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await b.newPage({ viewport: { width: 1440, height: 1100 } })
await p.addInitScript(() => window.localStorage.setItem('testplane:mock-role', 'admin'))
await p.goto('http://127.0.0.1:5181/runs?status=failed&page=2&page_size=10', { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
console.log('url:', p.url())
console.log('rail:', await p.locator('[data-rail]').getAttribute('data-rail'))
console.log('kpi cards:', await p.locator('[aria-label="概览指标"] > *').count())
console.log('table rows:', await p.locator('tbody tr').count())
console.log('queue summary:', await p.getByTestId('queue-summary').innerText())
console.log('nav items:', (await p.locator('aside[aria-label="主导航"] a').allInnerTexts()).join(' | '))
await p.screenshot({ path: '.data/layout/13-overview-merged-1440.png', fullPage: true })
await p.setViewportSize({ width: 1024, height: 900 })
await p.waitForTimeout(600)
await p.screenshot({ path: '.data/layout/14-overview-merged-1024.png', fullPage: true })
await b.close()